    p2 = run_arm(ev, "control", agents, mr, gen_wrong)
    print(f"[selftest] all-correct stub -> preserved={p1[0]} rec_maj={p1[1]} calls={p1[3]}")
    print(f"[selftest] all-wrong  stub -> preserved={p2[0]} rec_maj={p2[1]} calls={p2[3]}")
    assert p1[0] is True and p1[1] is True, "correct stub should preserve+recover"
    assert p2[0] is False and p2[1] is False, "wrong stub should not preserve"
