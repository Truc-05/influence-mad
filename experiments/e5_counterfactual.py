"""
E5 — Counterfactual intervention via clean re-query (FIRST GPU experiment).

For each behavioral-extinction event we know the death transition t*-1 -> t*:
a correct hypothesis is alive at t*-1 and gone at t*. E5 asks: if we intervene at
the trigger (t*-1), does the correct hypothesis survive the next revision, and
does the final outcome recover?

CLEAN COUNTERFACTUAL (the whole point): we take ONLY the logged prefix up to the
trigger round (rounds[0..t*-1], as generated by the original models) and RE-QUERY
the model forward under each arm. We NEVER replay the logged future (rounds >= t*)
because intervening changes the history each agent conditions on. Both the control
arm (factual re-query, original prompt) and the intervention arms regenerate from
t* forward under the SAME decoding protocol, so any difference is the intervention
effect, not re-query stochasticity or a model swap.

Arms:
  control            : original refine prompt (measures how often a plain re-query
                       already avoids the extinction -> the stochastic baseline)
  self_verify        : must find a concrete error before abandoning previous answer
  influence_resistant: re-derive independently; don't move just because peers agree
  combined           : both

Applied to ALL agents at the trigger and every re-queried round (deployable: no
gold, no need to know who holds the correct answer -> matches the Option-1
mechanism-agnostic bundle).

Outcomes (robustly scored):
  preservation = >=1 agent correct at the re-queried trigger round t*
  recovery_maj = majority of final re-queried answers correct
  recovery_any = >=1 agent correct at the end
  cost         = model calls (= 3 * re-queried rounds)

Report each arm vs the control re-query. Gate: intervention preservation/recovery
clearly above control. Run first on gsm8k + bbh (two regimes).

Usage:
  python experiments/e5_counterfactual.py --selftest         # stub, no GPU
  python experiments/e5_counterfactual.py --smoke 3 --bench gsm8k
  python experiments/e5_counterfactual.py --bench gsm8k,bbh --per-bench 40
"""
