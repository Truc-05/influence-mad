ARMS = ["control", "self_verify", "influence_resistant", "combined"]
CLAUSE = {
    "control": "",
    "self_verify": (
        "\nBefore you change your previous answer, explicitly identify the concrete "
        "error in your previous reasoning. If you cannot point to a specific error, "
        "keep your previous answer."),
    "influence_resistant": (
        "\nDo not change your answer merely because the other agents agree with each "
        "other. Re-derive the answer independently from the question itself; change "
        "only if your own independent derivation contradicts your previous answer."),
}
CLAUSE["combined"] = CLAUSE["self_verify"] + CLAUSE["influence_resistant"]

_REFINE = """{persona}

Question: {question}

Your previous answer: {own_answer}
Your previous reasoning: {own_reasoning}

Other agents proposed these answers in the previous round:
{peer_block}

Reconsider your answer. Keep it if you still believe it is correct, or revise it
if another agent's reasoning exposes a real error in yours. Do not change just to
agree — change only if convinced.{clause}
Respond in this exact format:
REASONING: <your updated step-by-step reasoning>
ANSWER: <your final answer, short and direct>
"""


def _norm(t):
    return (t or "").strip().lower()


def build_prompt(persona_text, question, own, peers, clause):
    peer_block = "\n".join(
        f"- Agent '{n}' answered: {r['answer']}  (because: {r['reasoning']})"
        for n, r in peers.items()) or "(none)"
    return _REFINE.format(persona=persona_text, question=question,
                          own_answer=own["answer"], own_reasoning=own["reasoning"],
                          peer_block=peer_block, clause=clause)


def build_agents(config):
    dc = config["debate"]
    return {s["name"]: PeerAgent(model_name=s["model"], role=s["name"],
                                 temperature=s.get("temperature", 0.3), base_url=dc["base_url"],
                                 max_tokens=dc.get("max_tokens", 512),
                                 timeout=dc.get("timeout_seconds", 180),
                                 persona=s.get("persona", "careful"))
            for s in config["agents"]}


def run_arm(event, arm, agents, max_rounds, gen_fn):
    """Re-query forward from the logged trigger state under one arm.
    event: dict(question, gt, ca, bench, names, trigger_state, t_star)
    gen_fn(agent, prompt) -> AgentResponse. Returns (preserved, rec_maj, rec_any, calls)."""
    names = event["names"]; q = event["question"]
    bench, gt, ca = event["bench"], event["gt"], event["ca"]
    clause = CLAUSE[arm]
    # state = {name: {"answer","reasoning"}} at t*-1 (from the logged prefix ONLY)
    prev = {n: dict(event["trigger_state"][n]) for n in names}
    calls = 0
    preserved = None
    t = event["t_star"]
    r = t
    while r < max_rounds:
        curr = {}
        for n in names:
            peers = {o: prev[o] for o in names if o != n}
            prompt = build_prompt(agents[n].persona_text, q, prev[n], peers, clause)
            resp = gen_fn(agents[n], prompt)
            curr[n] = {"answer": resp.answer, "reasoning": resp.reasoning}
            calls += 1
        if r == t:   # immediately after the intervened revision
            preserved = any(_correct(curr[n]["answer"], curr[n]["reasoning"], gt, bench, ca)
                            for n in names)
        prev = curr
        if len({_norm(curr[n]["answer"]) for n in names}) == 1:   # consensus stop
            break
        r += 1
    rec_any = any(_correct(prev[n]["answer"], prev[n]["reasoning"], gt, bench, ca) for n in names)
    mj = _majority(prev)
    rec_maj = _correct(mj["answer"], mj["reasoning"], gt, bench, ca)
    return bool(preserved), bool(rec_maj), bool(rec_any), calls


def _correct(ans, rea, gt, bench, ca):
    ra = robust_answer(ans, rea or "", bench)
    return (ra is not None) and is_correct(ra, gt, bench, ca)


def _majority(state):
    vals = [_norm(v["answer"]) for v in state.values()]
    key = max(set(vals), key=vals.count)
    for v in state.values():
        if _norm(v["answer"]) == key:
            return v
    return list(state.values())[0]


def load_events(benches, cap):
    """Behavioral-extinction events, at trigger round t*-1, from logs."""
    events = []
    for bench in benches:
        cnt = 0
        for f in sorted(glob.glob(f"data/debate_logs/{bench}_seed*.jsonl")):
            for lg in read_jsonl(f):
                p = prep_log(lg, bench)
                ext = extinction_of(p)
                if ext is None:
                    continue
                t = ext[0]
                trigger_state = {n: {"answer": lg["rounds"][t - 1]["answers"][n]["answer"],
                                     "reasoning": lg["rounds"][t - 1]["answers"][n]["reasoning"]}
                                 for n in p["agents"]}
                events.append({"question": lg["question"], "gt": lg["ground_truth"],
                               "ca": lg.get("correct_answers"), "bench": bench,
                               "names": p["agents"], "trigger_state": trigger_state,
                               "t_star": t, "mechanism": ext[1], "qid": lg["question_id"]})
                cnt += 1
                if cap and cnt >= cap:
                    break
            if cap and cnt >= cap:
                break
    return events


def summarize(results):
    out = {}
    for arm in ARMS:
        rs = [r[arm] for r in results if arm in r]
        n = len(rs)
        out[arm] = {"n": n,
                    "preservation": sum(x[0] for x in rs) / n if n else 0.0,
                    "recovery_maj": sum(x[1] for x in rs) / n if n else 0.0,
                    "recovery_any": sum(x[2] for x in rs) / n if n else 0.0,
                    "mean_calls": sum(x[3] for x in rs) / n if n else 0.0}
    return out


